const test = require('node:test');
const assert = require('node:assert/strict');
const Module = require('node:module');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { WidgetStore } = require('../src/main/widget-store.cjs');
const handlers = new Map();
const originalLoad = Module._load;
Module._load = function(name, ...args) {
  if (name === 'electron') return {ipcMain:{handle:(channel,handler)=>handlers.set(channel,handler),removeHandler:channel=>handlers.delete(channel)}};
  return originalLoad.call(this,name,...args);
};
const { registerHandlers, unregisterWidgetHandlers } = require('../src/main/ipc.cjs');
Module._load = originalLoad;

test('todo IPC binds mutations to its own enabled renderer and blocks control/music/edit-mode/spoofing', t => {
  const directory=path.join(__dirname,'../.tmp/tests',`todo-ipc-${randomUUID()}`);
  t.after(()=>{unregisterWidgetHandlers();fs.rmSync(directory,{recursive:true,force:true});});
  const store=new WidgetStore(directory);
  const todo=store.create('todo'),music=store.create('music');
  const control={},todoSender={},musicSender={};
  const windows=new Map([[todo.id,{webContents:todoSender,isDestroyed:()=>false}],[music.id,{webContents:musicSender,isDestroyed:()=>false}]]);
  todoSender.send=()=>{};
  const widgetWindows={windows,editMode:false};
  const reminderSender={};let dismissed=false,previewed=false;
  registerHandlers({store,widgetWindows,getControlWindow:()=>({webContents:control}),reminderWindow:{items:[],sync:()=>{},preview:()=>{previewed=true;},requireSender:sender=>{if(sender!==reminderSender)throw new Error('提醒窗口');},dismiss:()=>{dismissed=true;}}});
  const before=store.list();
  for(const sender of [todoSender,musicSender,{}]) assert.throws(()=>handlers.get('todo-reminder:preview')({sender}),/主窗口/);
  handlers.get('todo-reminder:preview')({sender:control});assert.equal(previewed,true);
  assert.deepEqual(store.list(),before);
  const add=handlers.get('todo:add'),complete=handlers.get('todo:complete');
  const input={text:'测试安全边界',color:'green',remindAt:null};
  for(const sender of [control,musicSender,{}]) assert.throws(()=>add({sender},input),/待办磁贴/);
  assert.throws(()=>add({sender:todoSender},{...input,color:'invalid'}),/预设颜色/);
  const items=add({sender:todoSender},input);
  assert.equal(items.length,1);
  const move=handlers.get('todo:move');
  for(const sender of [control,musicSender,{}]) assert.throws(()=>move({sender},items[0].id,null),/待办磁贴/);
  assert.deepEqual(move({sender:todoSender},items[0].id,null),items);
  assert.throws(()=>complete({sender:musicSender},items[0].id),/待办磁贴/);
  widgetWindows.editMode=true;assert.throws(()=>complete({sender:todoSender},items[0].id),/待办磁贴/);
  assert.throws(()=>move({sender:todoSender},items[0].id,null),/待办磁贴/);
  widgetWindows.editMode=false;store.setEnabled(todo.id,false);
  assert.throws(()=>add({sender:todoSender},input),/待办磁贴/);
  assert.throws(()=>move({sender:todoSender},items[0].id,null),/待办磁贴/);
  store.setEnabled(todo.id,true);assert.equal(complete({sender:todoSender},items[0].id).length,0);
  assert.throws(()=>handlers.get('todo-reminder:dismiss')({sender:control}),/提醒窗口/);
  handlers.get('todo-reminder:dismiss')({sender:reminderSender});assert.equal(dismissed,true);
  unregisterWidgetHandlers();assert.equal(handlers.size,0);
});
