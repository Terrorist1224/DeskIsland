const test = require('node:test');
const assert = require('node:assert/strict');
const Module = require('node:module');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { WidgetStore } = require('../src/main/widget-store.cjs');
const { Countdown } = require('../src/main/countdown.cjs');
const handlers=new Map(),originalLoad=Module._load;
Module._load=function(name,...args){if(name==='electron')return {ipcMain:{handle:(c,h)=>handlers.set(c,h),removeHandler:c=>handlers.delete(c)}};return originalLoad.call(this,name,...args);};
const {registerHandlers,unregisterWidgetHandlers}=require('../src/main/ipc.cjs');
Module._load=originalLoad;
test('countdown IPC validates sender, presets and duration; switch/removal cancel active runs', async t => {
  const directory=path.join(__dirname,'../.tmp/tests',`countdown-ipc-${randomUUID()}`);
  t.after(()=>{unregisterWidgetHandlers();fs.rmSync(directory,{recursive:true,force:true});});
  const store=new WidgetStore(directory),widget=store.create('countdown');
  const sender={send:()=>{}},control={};
  const widgetWindows={windows:new Map([[widget.id,{webContents:sender,isDestroyed:()=>false}]]),editMode:false,remove:()=>{},show:()=>{},setCountdownReminder:async()=>{}};
  const removed=[];
  const countdown=new Countdown({onDue:()=>{},onChange:()=>{},onError:()=>{}});
  registerHandlers({store,widgetWindows,countdown,getControlWindow:()=>({webContents:control}),reminderWindow:{sync:()=>{},removeCountdown:id=>removed.push(id)}});
  const call=(action,input)=>handlers.get('countdown:action')({sender},action,input);
  assert.throws(()=>handlers.get('countdown:action')({sender:control},'start',{seconds:3}));
  assert.throws(()=>call('start',{seconds:0}));assert.throws(()=>call('add',{name:' ',seconds:3}));
  const preset=call('add',{name:'泡面',seconds:180}).presets[0];
  assert.equal(call('start',{id:preset.id}).state.name,'泡面');
  assert.throws(()=>call('start',{seconds:1}));
  call('delete',{id:preset.id});assert.equal(call('get').state.name,'泡面');
  assert.equal(call('pause').state.status,'paused');assert.equal(call('resume').state.status,'running');
  widgetWindows.editMode=true;assert.throws(()=>call('cancel'));assert.equal(call('get').state.status,'running');widgetWindows.editMode=false;
  handlers.get('widgets:set-enabled')({sender:control},widget.id,false);assert.equal(countdown.get(widget.id).status,'idle');
  assert.throws(()=>call('start',{seconds:3}));store.setEnabled(widget.id,true);
  call('start',{seconds:1});countdown.states.get(widget.id).deadline=0;countdown.tick();
  assert.equal(call('get').state.status,'finished');assert.throws(()=>call('cancel'));
  assert.equal((await call('acknowledge')).state.status,'idle');assert.deepEqual(removed,[widget.id,widget.id]);
  call('start',{seconds:3});handlers.get('widgets:remove')({sender:control},widget.id);assert.equal(countdown.get(widget.id).status,'idle');assert.deepEqual(removed,[widget.id,widget.id,widget.id]);
});
